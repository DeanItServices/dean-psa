-- Fixes an erroneous @unique constraint on TimeEntry.invoiceLineItemId that
-- inverted the intended one-to-many relationship (InvoiceLineItem.timeEntries
-- is documented and used as InvoiceLineItem having MANY TimeEntry rows, e.g.
-- generateInvoice's tx.timeEntry.updateMany() in src/lib/actions/invoices.ts
-- assigns the same lineItem.id to every consumed TimeEntry in a billing
-- period). With the unique index live, that updateMany() throws a Postgres
-- unique-violation (P2002) as soon as a billing period contains more than
-- one billable time entry -- the normal case, not an edge case.
--
-- This migration was generated by hand rather than via
-- `npx prisma migrate dev --create-only`, because the prior migration
-- (20260901020532_add_time_tracking_billing) was hand-appended with an
-- out-of-band partial-index SQL statement after being applied (per its own
-- header comment and 04-01-SUMMARY.md), which changed its checksum. Prisma's
-- migrate dev therefore refuses to proceed without a full
-- `prisma migrate reset` (destructive, drops all data) due to perceived
-- drift. To avoid data loss, this migration file was authored manually,
-- matching the project's established convention (see 04-01-SUMMARY.md) of
-- hand-editing migration.sql for changes applied directly via
-- `docker exec ... psql` and recorded here for migration history.

-- DropIndex
DROP INDEX "TimeEntry_invoiceLineItemId_key";
